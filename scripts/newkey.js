// Creates a BRAND-NEW throwaway deployer account for Monad testnet and writes
// it into .env for you. Testnet only — never put real money in this account.
// Run:  node scripts/newkey.js
const fs = require("fs");
const path = require("path");
const { Wallet } = require("ethers");

const envPath = path.join(__dirname, "..", ".env");

if (fs.existsSync(envPath)) {
  const existing = fs.readFileSync(envPath, "utf8");
  const m = existing.match(/^PRIVATE_KEY=(0x[0-9a-fA-F]{64})\s*$/m);
  if (m) {
    const w = new Wallet(m[1]);
    console.log("\nYou already have a deployer account in .env — keeping it.\n");
    console.log("  YOUR ADDRESS:  " + w.address + "\n");
    console.log("Fund it with test MON at https://faucet.monad.xyz, then run: npm run deploy\n");
    process.exit(0);
  }
}

const w = Wallet.createRandom();
const body = [
  "# Throwaway Monad TESTNET deployer account, generated by scripts/newkey.js.",
  "# Never send real funds here. This file is gitignored and stays on your PC.",
  "PRIVATE_KEY=" + w.privateKey,
  "MONAD_RPC=https://testnet-rpc.monad.xyz",
  "",
].join("\n");

fs.writeFileSync(envPath, body);

console.log("\nCreated a fresh deployer account and saved it to .env\n");
console.log("  YOUR ADDRESS:  " + w.address + "\n");
console.log("NEXT: copy that address, get free test MON at https://faucet.monad.xyz,");
console.log("      then run:  npm run deploy\n");
